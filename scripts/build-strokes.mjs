// Converts KanjiVG stroke SVGs into src/data/strokes.js (kana only).
//
// Usage: node scripts/build-strokes.mjs <dir-with-kanjivg-svgs>
// The SVGs come from https://github.com/KanjiVG/kanjivg/tree/master/kanji and are
// named by codepoint, e.g. 03042.svg for あ. Only the kana used by the app are read.

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ALL_CHARS } from '../src/data/kana.js'

const svgDir = process.argv[2]
if (!svgDir) {
  console.error('Usage: node scripts/build-strokes.mjs <dir-with-kanjivg-svgs>')
  process.exit(1)
}

const PATH_RE = /<path\s+id="kvg:([0-9a-f]{5})-s(\d+)"[^>]*?\sd="([^"]+)"/g
const SAFE_D = /^[MmLlHhVvCcSsQqTtZz0-9.,\-\s]+$/

const glyphs = [...new Set(ALL_CHARS.flatMap((c) => [...c.kana]))]
const out = {}
const missing = []

for (const ch of glyphs) {
  const code = ch.codePointAt(0).toString(16).padStart(5, '0')
  const file = join(svgDir, `${code}.svg`)
  if (!existsSync(file)) {
    missing.push(ch)
    continue
  }
  const strokes = [...readFileSync(file, 'utf8').matchAll(PATH_RE)]
    .filter((m) => m[1] === code)
    .sort((a, b) => Number(a[2]) - Number(b[2]))
    .map((m) => m[3].trim())
  if (!strokes.length || strokes.some((d) => !SAFE_D.test(d))) throw new Error(`Unexpected stroke data for ${ch} (${code})`)
  out[ch] = strokes
}

if (missing.length) throw new Error(`Missing SVGs for: ${missing.join(' ')}`)

const header = `// Generated by scripts/build-strokes.mjs — do not edit by hand.
//
// Stroke data from KanjiVG (https://kanjivg.tagaini.net), Copyright (C) Ulrich Apel,
// licensed under Creative Commons Attribution-Share Alike 3.0
// (https://creativecommons.org/licenses/by-sa/3.0/). This file is shared under the same license.
//
// Each kana maps to its strokes in writing order, as SVG path data in a 109×109 box.
`
const body = Object.entries(out)
  .map(([ch, strokes]) => `  '${ch}': ${JSON.stringify(strokes)},`)
  .join('\n')

const target = join(dirname(fileURLToPath(import.meta.url)), '../src/data/strokes.js')
writeFileSync(target, `${header}\nexport default {\n${body}\n}\n`)
console.log(`Wrote ${Object.keys(out).length} glyphs to src/data/strokes.js`)
